    public function index()
    {
        $categories = self::getCatalog();

        return view('pages.services.index', compact('categories'));
    }

    public function category(string $category)
    {
        $catalog = self::getCatalog();
        $cat = $catalog[$category] ?? abort(404);
        $related = array_slice(array_filter($catalog, fn ($c) => $c['slug'] !== $category), 0, 4);

        return view('pages.services.category', compact('cat', 'related'));
    }

    public function subcategory(string $category, string $subcategory)
    {
        $catalog = self::getCatalog();
        $cat = $catalog[$category] ?? abort(404);
        $sub = collect($cat['subcategories'])->firstWhere('slug', $subcategory) ?? abort(404);

        return view('pages.services.subcategory', compact('cat', 'sub'));
    }

    public function show(string $category, string $subcategory, string $service)
    {
        $catalog = self::getCatalog();
        $cat = $catalog[$category] ?? abort(404);
        $sub = collect($cat['subcategories'])->firstWhere('slug', $subcategory) ?? abort(404);

        return view('pages.services.show', compact('cat', 'sub', 'service'));
    }
